`timescale 1ns/1ps

module rv32i_imm_gen (
    input  [31:0] instr,

    output reg [31:0] imm_i,
    output reg [31:0] imm_s,
    output reg [31:0] imm_b,
    output reg [31:0] imm_u,
    output reg [31:0] imm_j
);

    always @(*) begin

        // --------------------------------------------------------
        // I-type
        //
        // imm[11:0] = instr[31:20]
        // --------------------------------------------------------

        imm_i = {{20{instr[31]}},
                 instr[31:20]};


        // --------------------------------------------------------
        // S-type
        //
        // imm[11:5] = instr[31:25]
        // imm[4:0]  = instr[11:7]
        // --------------------------------------------------------

        imm_s = {{20{instr[31]}},
                 instr[31:25],
                 instr[11:7]};


        // --------------------------------------------------------
        // B-type
        //
        // imm[12]   = instr[31]
        // imm[11]   = instr[7]
        // imm[10:5] = instr[30:25]
        // imm[4:1]  = instr[11:8]
        // imm[0]    = 0
        // --------------------------------------------------------

        imm_b = {{19{instr[31]}},
                 instr[31],
                 instr[7],
                 instr[30:25],
                 instr[11:8],
                 1'b0};


        // --------------------------------------------------------
        // U-type
        // --------------------------------------------------------

        imm_u = {instr[31:12], 12'b0};


        // --------------------------------------------------------
        // J-type
        //
        // imm[20]    = instr[31]
        // imm[10:1]  = instr[30:21]
        // imm[11]    = instr[20]
        // imm[19:12] = instr[19:12]
        // imm[0]     = 0
        // --------------------------------------------------------

        imm_j = {{11{instr[31]}},
                 instr[31],
                 instr[19:12],
                 instr[20],
                 instr[30:21],
                 1'b0};

    end

endmodule
